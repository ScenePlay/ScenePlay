#!/usr/bin/env python3
"""Regenerate the verbatim-ported Broadcast page script for the SPA:

  web/app/views/ttrpg/obs_broadcast/console.js <- obs_broadcast.html's inline scripts

Same legacy-wrap shape as wrap_battlemap_js.py: the body becomes
`export function init(ctx, d, G)`, the `OBS_*_URL = url_for(...)` constants
become literal /ttrpg/obs paths, Jinja-injected values come from G,
document listeners go through ctx.on, location.reload() becomes _obsReload()
(scroll position kept across the re-mount), the 3 s state poll becomes an
`obs` SSE subscription with that poll as the fallback, and every top-level
function is exposed on window for the onclick="" attributes for the life of
the view."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FLASK = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / 'ScenePlay_Flask_Media_Wrapper'

# url_for('obs_bp.<endpoint>') -> path under /ttrpg/obs (routers/obs/__init__.py)
ENDPOINTS = {
    'api_state': '/api/state', 'api_switch': '/api/switch', 'api_refresh': '/api/refresh',
    'api_next': '/api/next', 'api_group': '/api/group', 'api_build_party': '/api/build-party',
    'api_output': '/api/output/__kind__', 'api_reorder': '/api/reorder',
    'api_card_override': '/api/card-override', 'api_map_mode': '/api/map-mode',
    'api_map_reload': '/api/map-reload', 'api_reload_sources': '/api/reload-sources',
    'api_map_scene': '/api/map-scene', 'api_on_stream': '/api/on-stream',
    'api_yt_link': '/api/yt/link', 'api_yt_link_poll': '/api/yt/link/poll',
    'api_yt_unlink': '/api/yt/unlink', 'api_yt_golive': '/api/yt/golive',
    'api_panel_note_save': '/api/panel-notes', 'api_panel_note_show': '/api/panel-notes/show',
    'api_panel_note_delete': '/api/panel-notes/delete', 'api_mute': '/api/mute',
    'api_scene_audio': '/api/scene-audio', 'api_new_room': '/api/room/new',
}

HEAD = '''// Verbatim port of obs_broadcast.html's inline scripts wrapped for the SPA —
// regenerated by scripts/wrap_obs_js.py; edit the generator, not this file.
import { exposeGlobals, unexposeGlobals } from '../../../lib/legacy.js';
import { toast } from '../../../ui/toast.js';

export function init(ctx, d, G) {
  let _dead = false;
  const OBS_SCROLL_KEY = 'obsCfgScroll';
  // The old page posted a form and reloaded; here a reload is a re-mount,
  // and the scroll position rides sessionStorage across it like before.
  function _obsReload() {
    try { sessionStorage.setItem(OBS_SCROLL_KEY, String(window.scrollY)); } catch (e) {}
    ctx.reload();
  }
  // The old form+redirect endpoints (art upload/clear, "back to the shared
  // look"): multipart POST, toast the {ok, message} answer, re-mount.
  async function _obsSubmitForm(form, submitter) {
    if (!form) return;
    const path = form.getAttribute('action');
    let res, body;
    try {
      res = await fetch(path, { method: 'POST', body: new FormData(form, submitter || undefined) });
      body = await res.json().catch(() => ({}));
    } catch (e) { toast.error('Could not reach ScenePlay.'); return; }
    if (!res.ok || (body && body.ok === false)) { toast.error((body && (body.error || body.message)) || ('HTTP ' + res.status)); return; }
    if (body && body.message) toast.success(body.message);
    _obsReload();
  }
'''

FOOT = '''
  const NAMES = {names};
  exposeGlobals({{ {expose} }});
  return () => {{
    _dead = true;
{cleanup}
    unexposeGlobals(NAMES);
  }};
}}
'''


def names_of(body):
    return list(dict.fromkeys(re.findall(r'^(?:async )?function (\w+)', body, re.M)))


def indent(body):
    return '\n'.join(('  ' + l) if l.strip() else l for l in body.split('\n'))


def build():
    html = (FLASK / 'templates' / 'ttrpg' / 'obs_broadcast.html').read_text()
    scripts = re.findall(r'<script>\n(.*?)</script>', html, re.S)
    assert len(scripts) == 2, len(scripts)
    body = '\n'.join(scripts)

    def url(m):
        name, kw = m.group(1), m.group(2) or ''
        path = '/ttrpg/obs' + ENDPOINTS[name]
        assert not kw or "kind='__kind__'" in kw, kw
        return f'"{path}"'
    body = re.sub(r'''"\{\{ url_for\('obs_bp\.(\w+)'(, [^)]*)?\) \}\}"''', url, body)
    body = body.replace('"{{ cfg.card_base_suggested }}"', 'G.CARD_BASE_SUGGESTED')
    body = body.replace('''"{{ 'device' if cfg.obs_local else 'feed' }}"''', 'G.MUSIC_AUTO')
    body = body.replace('{{ cfg.map_mode | tojson }}', 'G.MAP_MODE')
    assert '{{' not in body and '{%' not in body, [l for l in body.splitlines() if '{{' in l or '{%' in l]

    body = body.replace('location.reload()', '_obsReload()')
    body = body.replace('document.addEventListener(', 'ctx.on(document, ')
    # The scroll-restore listener (form submit + DOMContentLoaded): the SPA's
    # mount does the restore, and the settings form never submits any more.
    start = body.index("ctx.on(document, 'DOMContentLoaded', function () {\n  const form = document.getElementById('obs-cfg-form');")
    end = body.index('\n});\n', start) + len('\n});\n')
    body = body[:start] + body[end:]
    # Remaining DOMContentLoaded blocks run immediately: the view is rendered before init()
    body = re.sub(r"ctx\.on\(document, 'DOMContentLoaded', function \(\) \{(.*?)\n\}\);", lambda m: '(function () {' + m.group(1) + '\n})();', body, flags=re.S)
    body = body.replace("ctx.on(document, 'DOMContentLoaded', obsPaintMusicPath);", 'obsPaintMusicPath();')
    assert 'DOMContentLoaded' not in body
    # the wrapper head owns this constant (used by _obsReload above the body)
    body = body.replace("const OBS_SCROLL_KEY = 'obsCfgScroll';\n", '')
    assert body.count('OBS_SCROLL_KEY') == 0
    # "Choose existing" art: submit the slot's form through the SPA, not the browser
    body = body.replace('    ref.value = spAssetRef(it, \'obs\');\n    form.submit();', '    ref.value = spAssetRef(it, \'obs\');\n    _obsSubmitForm(form);')
    assert 'form.submit()' not in body
    # The 3 s state poll: pushed by the `obs` SSE topic, the poll as the fallback
    body = body.replace('function obsPoll() {\n', 'function obsPoll() {\n  if (_dead) return;\n', 1)
    body = body.replace('obsPoll();\nsetInterval(obsPoll, 3000);',
                        "obsPoll();\nctx.subscribe('obs', () => obsPoll(), { fallback: { every: 3000, fetch: async () => null } });\nctx.every(15000, obsPoll);   // belt and braces: rows/presence have no event of their own")
    assert 'setInterval(' not in body

    names = names_of(body) + ['_obsReload', '_obsSubmitForm']
    cleanup = '''    try { clearTimeout(_ytPollTimer); } catch (e) {}
    try { clearTimeout(_obsSaveTimer); } catch (e) {}
    document.querySelectorAll('#obs-saved-pill').forEach(el => el.remove());'''
    out = HEAD + indent(body) + FOOT.format(names=json.dumps(names), expose=', '.join(names), cleanup=cleanup)
    (ROOT / 'web/app/views/ttrpg/obs_broadcast/console.js').write_text(out)
    return names


def check_onclicks(names, extra=()):
    html = (FLASK / 'templates' / 'ttrpg' / 'obs_broadcast.html').read_text()
    used = set(re.findall(r'on[a-z]+="([A-Za-z_$][A-Za-z0-9_$]*)\(', html))
    return sorted(u for u in used if u not in names and u not in extra and u not in ('if', 'confirm', 'document', 'window', 'var'))


if __name__ == '__main__':
    n = build()
    print('console.js globals:', len(n), 'missing:', check_onclicks(n, extra=('pasteImageNear', 'spPickAsset')))
