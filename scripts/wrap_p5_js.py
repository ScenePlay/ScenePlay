#!/usr/bin/env python3
"""Regenerate the verbatim-ported P5 page scripts for the SPA (reference API
settings, monsters library, monster card, homebrew form):

  web/app/views/ttrpg/reference/api_settings_page/script.js <- api_settings.html inline script
  web/app/views/ttrpg/monsters_page/script.js               <- monsters.html inline script
  web/app/views/ttrpg/monster_detail_page/script.js         <- monster_detail.html inline script
  web/app/views/ttrpg/monster_homebrew_page/script.js       <- monster_homebrew.html inline script

Each becomes `export function init(ctx, d, G)`: Jinja `{{ x | tojson }}` page
globals come from G, url_for() becomes literal paths, document listeners go
through ctx.on, location.reload -> ctx.reload, timers through ctx.after /
ctx.every, and every top-level function is exposed on window for the
onclick="" attributes for the life of the view."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FLASK = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / 'ScenePlay_Flask_Media_Wrapper'
TPL = FLASK / 'templates' / 'ttrpg'

HEAD = '''// Verbatim port of {src} wrapped for the SPA — regenerated by
// scripts/wrap_p5_js.py; edit the generator, not this file.
import {{ exposeGlobals, unexposeGlobals }} from '{lib}/legacy.js';

export function init(ctx, d, G) {{
  let _dead = false;
{globals}
'''

FOOT = '''
  const NAMES = {names};
  exposeGlobals({{ {expose} }});
  return () => {{
    _dead = true;
{cleanup}
    unexposeGlobals(NAMES);
  }};
}}
'''


def names_of(body):
    return list(dict.fromkeys(re.findall(r'^(?:async )?function (\w+)', body, re.M)))


def inline_scripts(html_name):
    """The page's own <script> blocks (not the <script src=...> includes)."""
    html = (TPL / html_name).read_text()
    return '\n'.join(re.findall(r'<script>\n(.*?)</script>', html, re.S))


def common(body):
    body = body.replace('document.addEventListener(', 'ctx.on(document, ')
    body = body.replace('window.addEventListener(', 'ctx.on(window, ')
    body = body.replace('location.reload()', 'ctx.reload()')
    # DOMContentLoaded blocks run immediately: the view is rendered before init()
    body = re.sub(r"^ctx\.on\(document, 'DOMContentLoaded', \(\) => \{$(.*?)^\}\);$",
                  lambda m: '(() => {' + m.group(1) + '})();', body, flags=re.M | re.S)
    return body


def indent(body):
    return '\n'.join(('  ' + l) if l.strip() else l for l in body.split('\n'))


def check(body, what):
    assert '{{' not in body and '{%' not in body and 'url_for(' not in body, f'unhandled Jinja in {what}'


def write(dst, src_label, lib, globs, body, cleanup='', extra_names=()):
    names = names_of(body) + list(extra_names)
    out = (HEAD.format(src=src_label, lib=lib, globals=globs) + indent(body)
           + FOOT.format(names=json.dumps(names), expose=', '.join(names), cleanup=cleanup))
    (ROOT / dst).write_text(out)
    return names


def build_api_settings():
    body = inline_scripts('api_settings.html')
    body = re.sub(r'const jobs = \[.*?\n  \];', 'const jobs = G.SYNC_JOBS;', body, count=1, flags=re.S)
    body = body.replace("fetch(`{{ url_for('reference_bp.api_test') }}?url=", "fetch(`/ttrpg/reference/settings/test?url=")
    check(body, 'api_settings')
    body = common(body)
    # the Sync All chain must stop with the view: every timer goes through ctx
    body = re.sub(r'setTimeout\((.+), (\d+)\);', r'ctx.after(\2, \1);', body)
    return write('web/app/views/ttrpg/reference/api_settings_page/script.js', 'api_settings.html inline script',
                 '../../../../lib', '  void d; void G;', body)


def build_monsters():
    body = inline_scripts('monsters.html')
    check(body, 'monsters')
    body = common(body)
    # the homebrew delete form is a data-api form now (the view submits it)
    body = body.replace("document.getElementById('homebrew-delete-form').action =",
                        "document.getElementById('homebrew-delete-form').dataset.api =")
    body = body.replace('.then(renderResults);', '.then(r => { if (!_dead) renderResults(r); });')
    cleanup = '    try { clearTimeout(searchTimer); } catch (e) {}'
    return write('web/app/views/ttrpg/monsters_page/script.js', 'monsters.html inline script',
                 '../../../lib', '  void d; void G;', body, cleanup)


def build_monster_detail():
    body = inline_scripts('monster_detail.html')
    body = re.sub(r'const MD_NAME\s*=.*?;', 'const MD_NAME = G.MD_NAME;', body, count=1)
    body = re.sub(r'const MD_INSTANCE\s*=.*?;', 'const MD_INSTANCE = G.MD_INSTANCE;', body, count=1)
    body = re.sub(r'const MD_HP_MAX\s*=.*?;', 'const MD_HP_MAX = G.MD_HP_MAX;', body, count=1)
    body = re.sub(r'const GAME_INFO = \{\{ game \| tojson \}\};', 'const GAME_INFO = G.GAME_INFO;', body, count=1)
    body = re.sub(r'setInterval\(\(\) => \{(.*?)\n\}, 10000\);', r'ctx.every(10000, () => {\1\n});', body, count=1, flags=re.S)
    check(body, 'monster_detail')
    body = common(body)
    return write('web/app/views/ttrpg/monster_detail_page/script.js', 'monster_detail.html inline script',
                 '../../../lib', '  void d;', body)


def build_monster_homebrew():
    body = inline_scripts('monster_homebrew.html')
    body = body.replace('const _ICON_GENRES = {{ icon_genres | tojson }};', 'const _ICON_GENRES = G.ICON_GENRES;')
    body = body.replace("fetch(`{{ url_for('monsters_bp.homebrew_random') }}?kind=", "fetch(`/ttrpg/monsters/homebrew/random?kind=")
    check(body, 'monster_homebrew')
    body = common(body)
    return write('web/app/views/ttrpg/monster_homebrew_page/script.js', 'monster_homebrew.html inline script',
                 '../../../lib', '  void d;', body)


def check_onclicks(html_name, names, extra=()):
    html = (TPL / html_name).read_text()
    used = set(re.findall(r'on[a-z]+="([A-Za-z_$][A-Za-z0-9_$]*)\(', html))
    return sorted(u for u in used if u not in names and u not in extra
                  and u not in ('if', 'confirm', 'document', 'window', 'var', 'event', 'return'))


if __name__ == '__main__':
    a = build_api_settings()
    m = build_monsters()
    md = build_monster_detail()
    mh = build_monster_homebrew()
    print('api_settings:', len(a), 'missing:', check_onclicks('api_settings.html', a))
    print('monsters:', len(m), 'missing:', check_onclicks('monsters.html', m, extra=('pasteImageNear',)))
    print('monster_detail:', len(md), 'missing:', check_onclicks('monster_detail.html', md))
    print('monster_homebrew:', len(mh), 'missing:', check_onclicks('monster_homebrew.html', mh, extra=('pasteImageNear', 'spPickAsset')))
