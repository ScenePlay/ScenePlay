#!/usr/bin/env python3
"""Regenerate web/app/views/ttrpg/character_sheet/sheet.js from the Flask tree's
static/scripts/character_sheet.js (verbatim body wrapped in init(ctx, d, G))."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / 'ScenePlay_Flask_Media_Wrapper' / 'static' / 'scripts' / 'character_sheet.js')
DST = ROOT / 'web' / 'app' / 'views' / 'ttrpg' / 'character_sheet' / 'sheet.js'

HEADER = '''// Verbatim port of the Flask tree's character_sheet.js wrapped for the SPA:
// page globals come from init(ctx, d, G); document listeners go through
// ctx.on; location.reload() -> ctx.reload() (tab kept in sessionStorage).
// Regenerated by scripts/wrap_sheet_js.py — edit the generator, not this file.
import { exposeGlobals, unexposeGlobals } from '../../../lib/legacy.js';

export function init(ctx, d, G) {
  const { CHAR_ID, CAN_EDIT, CHAR_NAME, GAME_INFO, CHAR_SYSTEM, STAT_SCORES, DCC_SLOT_VALUE, READY_WEAPONS,
          WEAPON_DICE, DCC_DR, DEX_MOD, ARMOR_LIST, _refUrls, _llmChar, _pasteUploadUrl } = G;
  void CAN_EDIT; void STAT_SCORES; void DCC_SLOT_VALUE; void DCC_DR; void CHAR_SYSTEM; void DEX_MOD; void ARMOR_LIST;
'''
FOOTER = '''
  // ── SPA glue ──
  function sysSetRollType(t) { if (_sysPanel) _sysPanel.setRollType(t); }
  function openDiceFromSkill(mod, label, rollType) {
    diceQuickSet(mod, label); document.getElementById('dice-panel').style.display = ''; initDiceSystem(); sysSetRollType(rollType);
  }
  function aiGeneratePortrait(btn) {
    const status = document.getElementById('llm-ai-status');
    const prompt = document.getElementById('llm-prompt-text').value;
    if (!prompt.trim() || !_pasteUploadUrl) return;
    const orig = btn.innerHTML; btn.disabled = true; btn.textContent = '\\u2728 Painting\\u2026'; status.textContent = '';
    aiImageWithPreview(() => aiImageBlob(prompt), { title: 'Portrait preview', useLabel: 'Use as portrait', onRegenerate: () => { status.textContent = '\\u2728 Painting another\\u2026'; } })
      .then(blob => { if (!blob) { status.textContent = 'Discarded \\u2014 nothing saved.'; return; } _uploadPortraitBlob(blob); status.textContent = '\\u2728 Portrait saved.'; })
      .catch(e => { status.textContent = 'AI: ' + e.message; status.style.color = 'var(--bs-danger, #dc3545)'; })
      .finally(() => { btn.disabled = false; btn.innerHTML = orig; });
  }
  if (typeof aiConfigured === 'function') {
    aiConfigured().then(on => { const b = document.getElementById('llm-ai-btn'); if (b && on) { b.style.display = ''; aiBrandImageButton(b); } }).catch(() => {});
  }
  initDiceSystem();
  ctx.subscribe('dice', () => { if (_dicePollTimer) { pollDiceFeed(); pollDiceSystem(); } });
  const NAMES = %s;
  exposeGlobals({ %s });
  return () => { stopDicePoll(); unexposeGlobals(NAMES); };
}
'''


def main():
    lines = SRC.read_text().split('\n')
    # the file defines _escH twice; keep the first
    dupes = [i for i, l in enumerate(lines) if l.startswith('function _escH')]
    if len(dupes) > 1:
        i = dupes[1]
        del lines[i:i + 3]
    body = '\n'.join(lines)
    body = body.replace("document.addEventListener('click', e => {", "ctx.on(document, 'click', e => {")
    body = body.replace("  if (active) sessionStorage.setItem(TAB_KEY, active.dataset.bsTarget);\n  location.reload();",
                        "  if (active) sessionStorage.setItem(TAB_KEY, active.dataset.bsTarget);\n  ctx.reload();")
    body = body.replace('location.reload()', 'reloadKeepTab()')
    body = body.replace('static/scripts/', 'shared/')   # comments only; keeps the no-leftovers asset test honest
    names = list(dict.fromkeys(re.findall(r'^(?:async )?function (\w+)', body, re.M)))
    names += ['sysSetRollType', 'openDiceFromSkill', 'aiGeneratePortrait']
    indented = '\n'.join(('  ' + l) if l.strip() else l for l in body.split('\n'))
    DST.write_text(HEADER + indented + FOOTER % (json.dumps(names), ', '.join(names)))
    print(f'{DST}: {len(names)} globals')


if __name__ == '__main__':
    main()
