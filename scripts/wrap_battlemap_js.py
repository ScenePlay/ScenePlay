#!/usr/bin/env python3
"""Regenerate the verbatim-ported battle map scripts for the SPA:

  web/app/views/ttrpg/battlemap/map.js         <- static/scripts/battlemap.js
                                                  + battlemap.html's inline 3D bridge
  web/app/views/ttrpg/battlemap_manage/manage.js <- battlemap_manage.html inline scripts

Each becomes `export function init(ctx, d, G)`: page globals come from G,
document/window listeners go through ctx.on, timers through ctx.every/after,
location.reload -> ctx.reload, and every top-level function is exposed on
window for the onclick="" attributes for the life of the view."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FLASK = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / 'ScenePlay_Flask_Media_Wrapper'

HEAD = '''// Verbatim port of {src} wrapped for the SPA — regenerated by
// scripts/wrap_battlemap_js.py; edit the generator, not this file.
import {{ exposeGlobals, unexposeGlobals }} from '../../../lib/legacy.js';

export function init(ctx, d, G) {{
  let _dead = false;
{globals}
'''

FOOT = '''
  const NAMES = {names};
  exposeGlobals({{ {expose} }});
  return () => {{
    _dead = true;
{cleanup}
    unexposeGlobals(NAMES);
  }};
}}
'''


def names_of(body):
    return list(dict.fromkeys(re.findall(r'^(?:async )?function (\w+)', body, re.M)))


def common(body):
    body = body.replace('document.addEventListener(', 'ctx.on(document, ')
    body = body.replace('window.addEventListener(', 'ctx.on(window, ')
    body = body.replace('location.reload()', 'ctx.reload()')
    # DOMContentLoaded blocks run immediately: the view is rendered before init()
    body = re.sub(r"^ctx\.on\(document, 'DOMContentLoaded', \(\) => \{$(.*?)^\}\);$",
                  lambda m: '(() => {' + m.group(1) + '})();', body, flags=re.M | re.S)
    return body


def indent(body):
    return '\n'.join(('  ' + l) if l.strip() else l for l in body.split('\n'))


def build_map():
    src = (FLASK / 'static' / 'scripts' / 'battlemap.js').read_text()
    html = (FLASK / 'templates' / 'ttrpg' / 'battlemap.html').read_text()
    # the inline 3D bridge (between the const block and </script>)
    m = re.search(r"const OBS_ENABLED\s*=.*?\n(.*?)\{% endif %\}\n</script>", html, re.S)
    bridge = m.group(1)
    bridge = bridge.replace('{% if bm3d_available %}\n', '')
    bridge = re.sub(r'const _BM3D_SRCS = \[.*?\];', "const _BM3D_SRCS = ['/shared/three.min.js', '/shared/battlemap3d.js'];", bridge, flags=re.S)
    body = common(src)
    body = body.replace("const _go = () => { window.location.href = `/ttrpg/battlemap/${d.active_map_id}/view`; };",
                        "const _go = () => { ctx.navigate(`/ttrpg/battlemap/${d.active_map_id}/view`); };")
    body = body.replace('  setInterval(pollRelayPresence, 15000);\n  setTimeout(pollRelayPresence, 3000);',
                        '  ctx.every(15000, pollRelayPresence);\n  ctx.after(3000, pollRelayPresence);')
    body = body.replace('setInterval(mapRefreshNowPlaying, 4000);', 'ctx.every(4000, mapRefreshNowPlaying);')
    body = body.replace('function pollState() {\n', 'function pollState() {\n  if (_dead) return;\n', 1)
    body = body.replace('function _schedulePoll() {\n', 'function _schedulePoll() {\n  if (_dead) return;\n', 1)
    body = body.replace('static/scripts/', 'shared/')
    bridge = common(bridge).replace('static/scripts/', 'shared/')
    names = names_of(body) + names_of(bridge)
    globs = '''  const { MAP_ID, GRID_COLS, GRID_ROWS, IS_DM, CURRENT_USER_ID, MAP_ROLLER_NAME, ROLLER_CHARS, GAME_INFO,
          SESSION_ID, COLLAPSE_INIT, FLOORPLAN_VERSION, BM3D_AVAILABLE, OBS_ENABLED } = G;
  let CELL_PX = G.CELL_PX, MOVE_SCALE = G.MOVE_SCALE;
  void MAP_ROLLER_NAME; void SESSION_ID; void FLOORPLAN_VERSION; void BM3D_AVAILABLE;'''
    cleanup = '''    try { if (pollTimer && pollTimer !== 1) clearTimeout(pollTimer); pollTimer = null; } catch (e) {}
    try { if (typeof _mapDicePoll !== 'undefined' && _mapDicePoll) clearInterval(_mapDicePoll); } catch (e) {}
    try { if (typeof _mapSysPoll !== 'undefined' && _mapSysPoll) clearInterval(_mapSysPoll); } catch (e) {}
    try { if (typeof _collapseTick !== 'undefined' && _collapseTick) clearInterval(_collapseTick); } catch (e) {}
    try { if (typeof _mapVolTimer !== 'undefined' && _mapVolTimer) clearTimeout(_mapVolTimer); } catch (e) {}
    try { if (window.BM3D && BM3D.isOpen()) BM3D.close(); } catch (e) {}
    window._bmLastState = null;'''
    glue = '''
  // ── SPA glue: SSE nudges (the poll chain stays as the fallback) ──
  ctx.subscribe('battlemap:' + MAP_ID, () => { if (!_dead && !activeDrag && !activeFxDrag) pollState(); });
  ctx.subscribe('nowplaying', () => { try { mapRefreshNowPlaying(); } catch (e) {} });
  ctx.subscribe('dice', () => { try { if (typeof _mapDicePoll !== 'undefined' && _mapDicePoll) mapPollFeed(); } catch (e) {} });
'''
    out = (HEAD.format(src="the Flask tree's battlemap.js (+ the map page inline 3D bridge)", globals=globs)
           + indent(body) + '\n\n  // ── 3D mode bridge (battlemap.html inline script) ──\n' + indent(bridge) + glue
           + FOOT.format(names=json.dumps(names), expose=', '.join(names), cleanup=cleanup))
    (ROOT / 'web/app/views/ttrpg/battlemap/map.js').write_text(out)
    return names


def build_manage():
    html = (FLASK / 'templates' / 'ttrpg' / 'battlemap_manage.html').read_text()
    scripts = re.findall(r'<script>\n(.*?)</script>', html, re.S)
    body = '\n'.join(scripts)
    body = re.sub(r'const _MAP_GENRES = \{\{ map_prompt_data \| tojson \}\};', 'const _MAP_GENRES = G.MAP_GENRES;', body)
    body = re.sub(r'const _FP_INFO = \{\{ floorplan_info \| tojson \}\};', 'const _FP_INFO = G.FP_INFO;', body)
    body = re.sub(r'const _mapBgPasteUrls = \{.*?\n\};', 'const _mapBgPasteUrls = G.BG_PASTE_URLS;', body, flags=re.S)
    assert '{{' not in body and '{%' not in body, 'unhandled Jinja in manage script'
    body = common(body)
    names = names_of(body)
    globs = '''  const { SESSION_ID } = G;
  void SESSION_ID;'''
    cleanup = '''    try { if (typeof _aiVideoTimer !== 'undefined' && _aiVideoTimer) clearInterval(_aiVideoTimer); } catch (e) {}'''
    out = (HEAD.format(src='battlemap_manage.html inline scripts', globals=globs) + indent(body)
           + FOOT.format(names=json.dumps(names), expose=', '.join(names), cleanup=cleanup))
    (ROOT / 'web/app/views/ttrpg/battlemap_manage/manage.js').write_text(out)
    return names


def check_onclicks(html_name, names, extra=()):
    html = (FLASK / 'templates' / 'ttrpg' / html_name).read_text()
    used = set(re.findall(r'on[a-z]+="([A-Za-z_$][A-Za-z0-9_$]*)\(', html))
    missing = sorted(u for u in used if u not in names and u not in extra and u not in ('if', 'confirm', 'document', 'window', 'var'))
    return missing


if __name__ == '__main__':
    mn = build_map()
    gn = build_manage()
    print('map.js globals:', len(mn), 'missing:', check_onclicks('battlemap.html', mn, extra=('BMFP', 'SFX')))
    print('manage.js globals:', len(gn), 'missing:', check_onclicks('battlemap_manage.html', gn, extra=('TexturePicker', 'spPickAsset')))
